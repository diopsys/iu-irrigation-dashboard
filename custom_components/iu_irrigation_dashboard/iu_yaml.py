"""Irrigation-Unlimited-Konfiguration aus den Einstellungen erzeugen.

Die Datei packages/iu_irrigation_dashboard.yaml gehört der Integration und wird bei
jeder Änderung neu geschrieben. Je Controller der Einstellungen (mit Pumpe
und mindestens einer Zone) ein IU-Controller mit seinen Zonen und Sequenzen;
je Plan einer Sequenz ein IU-Plan.

IU benennt seine Entitäten nach der Position: binary_sensor.irrigation_
unlimited_c{Controller}_m, …_c{C}_z{Zone}, …_c{C}_s{Sequenz}. Die Zuordnung
liefert zuordnung() – alle anderen Module nutzen nur diese Funktion.
"""

from __future__ import annotations

import logging
import os
import re
from pathlib import Path
from typing import Any

import voluptuous as vol
import yaml

from homeassistant.core import HomeAssistant

from .const import ANSCHLUSS_LEITUNG, BETRIEB_WASSERHAHN, IU_DATEI, IU_DOMAIN
from . import smart
from .einstellungen import pumpe_id

_LOGGER = logging.getLogger(__name__)

IU_PRAEFIX = "binary_sensor.irrigation_unlimited_"

KOPF = """\
# ==================================================================
# AUTOMATISCH ERZEUGT von der Integration „IU Irrigation Dashboard“ – nicht
# von Hand bearbeiten. Änderungen im Panel → Einstellungen.
# GENERATED by the IU Irrigation Dashboard integration – do not edit.
# Die Datei wird bei jeder Änderung überschrieben und danach per
# irrigation_unlimited.reload geladen.
# ==================================================================
"""


def _hhmmss(sekunden: int) -> str:
    sekunden = max(0, int(sekunden))
    return f"{sekunden // 3600:02d}:{sekunden % 3600 // 60:02d}:{sekunden % 60:02d}"


def iu_controller(daten: dict[str, Any]) -> list[dict[str, Any]]:
    """Controller, die in die IU-Datei kommen (mindestens eine Zone und eine
    Pumpe oder der Wasseranschluss)."""
    return [c for c in daten["controller"]
            if c["zonen"] and (c["anschluss"] == ANSCHLUSS_LEITUNG or pumpe_id(c))]


def iu_sequenzen(ctl: dict[str, Any]) -> list[dict[str, Any]]:
    """Sequenzen eines Controllers, die in die IU-Datei kommen (mit Zonen)."""
    return [s for s in ctl["sequenzen"] if s["zonen"]]


def zuordnung(daten: dict[str, Any]) -> dict[str, Any]:
    """IDs der Einstellungen → IU-Entitäten.

    {"controller": {ctl_id: entity}, "zonen": {zone_id: entity},
     "sequenzen": {seq_id: entity}, "zone_nr": {zone_id: n (1-basiert)}}
    """
    erg: dict[str, Any] = {"controller": {}, "zonen": {}, "sequenzen": {}, "zone_nr": {}}
    for ci, ctl in enumerate(iu_controller(daten), start=1):
        erg["controller"][ctl["id"]] = f"{IU_PRAEFIX}c{ci}_m"
        for zi, zone in enumerate(ctl["zonen"], start=1):
            erg["zonen"][zone["id"]] = f"{IU_PRAEFIX}c{ci}_z{zi}"
            erg["zone_nr"][zone["id"]] = zi
        for si, seq in enumerate(iu_sequenzen(ctl), start=1):
            erg["sequenzen"][seq["id"]] = f"{IU_PRAEFIX}c{ci}_s{si}"
    return erg


def zone_nach_id(ctl: dict[str, Any], zone_id: str) -> dict[str, Any] | None:
    return next((z for z in ctl["zonen"] if z["id"] == zone_id), None)


def seq_zone_aktiv(ctl: dict[str, Any], sz: dict[str, Any]) -> bool:
    """Läuft dieser Eintrag der Sequenz in der Automatik?"""
    zone = zone_nach_id(ctl, sz["zone"])
    if zone is None or not sz["aktiv"]:
        return False
    return not (zone["wasserhahn"] and zone["betrieb"] == BETRIEB_WASSERHAHN)


def seq_zone_dauer(ctl: dict[str, Any], sz: dict[str, Any]) -> int:
    """Dauer in min (eigene Dauer der Sequenz oder Standardlaufzeit der Zone)."""
    zone = zone_nach_id(ctl, sz["zone"])
    return sz["dauer_min"] or (zone["standard_min"] if zone else 20)


def seq_eintrag(ctl: dict[str, Any], sz: dict[str, Any], runde: int, nr: dict[str, int],
                mit_smart: bool = False) -> dict[str, Any]:
    """Eintrag einer Sequenzzone in der IU-Datei (runde > 0: weiterer
    Durchgang beim Aufteilen, Sickerpause als Pause nach dem Durchgang)."""
    eintrag: dict[str, Any] = {
        "zone_id": str(nr[sz["zone"]]),
        "duration": _hhmmss(seq_zone_dauer(ctl, sz) * 60),
        "enabled": seq_zone_aktiv(ctl, sz),
    }
    zone = zone_nach_id(ctl, sz["zone"])
    if (mit_smart and zone and zone["smart"]["aufteilen"] and zone["smart"]["sickerpause_min"]
            and runde < smart.durchgaenge_max(zone) - 1):
        eintrag["delay"] = _hhmmss(zone["smart"]["sickerpause_min"] * 60)
    return eintrag


def vollstaendig(daten: dict[str, Any]) -> str | None:
    """None, wenn sich eine IU-Konfiguration erzeugen lässt, sonst der Grund."""
    if not daten["controller"]:
        return "Es ist noch kein Controller angelegt"
    if not iu_controller(daten):
        return "Kein Controller hat mindestens eine Zone und eine Pumpe oder einen Wasseranschluss"
    return None


def _zeit(plan: dict[str, Any]) -> Any:
    zeit = plan["zeit"]
    if zeit["bezug"] == "uhrzeit":
        return zeit["uhrzeit"] + ":00"
    sonne = "sunrise" if zeit["bezug"] == "sonnenaufgang" else "sunset"
    versatz = zeit["versatz_min"]
    return {"sun": sonne, "before" if versatz < 0 else "after": _hhmmss(abs(versatz) * 60)}


def erzeugen(daten: dict[str, Any]) -> dict[str, Any]:
    """IU-Konfiguration als dict (Inhalt unter irrigation_unlimited:)."""
    controller = []
    for ctl in iu_controller(daten):
        pumpe = ctl["pumpe"]
        nr = {z["id"]: i for i, z in enumerate(ctl["zonen"], start=1)}
        eintrag: dict[str, Any] = {"name": ctl["name"]}
        if pumpe_id(ctl):
            eintrag.update({
                "entity_id": pumpe["entity_id"],
                # IU schaltet die Pumpe nur ein; aus schaltet die Integration
                # (nach dem Lauf bzw. abends beim Tagbetrieb)
                "entity_states": "on",
                "check_back": {"states": "on"},
                "preamble": _hhmmss(pumpe["vorlauf_s"]),
                "postamble": _hhmmss(pumpe["nachlauf_s"]),
            })
        # Wasseranschluss: kein Controller-Schalter, die Ventile hängen an der Leitung
        eintrag["zones"] = [
            {"name": z["name"], "entity_id": z["ventile"] if len(z["ventile"]) > 1 else z["ventile"][0]}
            for z in ctl["zonen"]
        ]
        sequenzen = []
        for seq in iu_sequenzen(ctl):
            plaene = [
                {
                    "name": plan["name"],
                    "schedule_id": f"{seq['id']}_{plan['key']}",
                    "time": _zeit(plan),
                    # IU braucht nicht-leere Listen; ohne Monate/Tage ist der Plan aus
                    "weekday": plan["tage"] or ["mon"],
                    "month": plan["monate"] or ["jan"],
                    "enabled": bool(plan["monate"]) and bool(plan["tage"]),
                }
                for plan in seq["plaene"]
            ]
            s_eintrag: dict[str, Any] = {
                "name": seq["name"],
                "delay": _hhmmss(seq["pause_s"]),
                "zones": [seq_eintrag(ctl, sz, runde, nr, smart.aktiv(daten))
                          for sz, runde in smart.iu_eintraege(ctl, seq, smart.aktiv(daten))],
            }
            if plaene:
                s_eintrag["schedules"] = plaene
            sequenzen.append(s_eintrag)
        if sequenzen:
            eintrag["sequences"] = sequenzen
        controller.append(eintrag)

    return {
        "refresh_interval": 15,
        # Historie: IU liest sonst alle 2 min die Zustände seiner Entitäten
        # aus der Datenbank (Speicherlast). Laufzeiten
        # zählt die Integration selbst.
        "history": {"enabled": bool(daten["iu"]["historie"])},
        "controllers": controller,
    }


def pruefen_mit_iu_schema(hass: HomeAssistant | None, konfig: dict[str, Any]) -> str | None:
    """Mit dem Schema von Irrigation Unlimited prüfen. None = gültig."""
    try:
        from custom_components.irrigation_unlimited.schema import (  # pylint: disable=import-outside-toplevel
            IRRIGATION_SCHEMA,
        )
    except ImportError:
        return None  # IU nicht installiert – Prüfung beim Laden
    try:
        IRRIGATION_SCHEMA(konfig)
    except vol.Invalid as err:
        return str(err)
    return None


class _Dumper(yaml.SafeDumper):
    """Zeiten wie 00:20:00 in Anführungszeichen – YAML 1.1 läse sie sonst als
    Zahl zur Basis 60."""


def _str_darstellen(dumper: yaml.SafeDumper, wert: str) -> yaml.Node:
    stil = "'" if re.fullmatch(r"\d+(:\d+)+", wert) else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", wert, style=stil)


_Dumper.add_representer(str, _str_darstellen)


def als_text(konfig: dict[str, Any]) -> str:
    return KOPF + yaml.dump(
        {IU_DOMAIN: konfig}, Dumper=_Dumper, allow_unicode=True, sort_keys=False,
        default_flow_style=False, width=100,
    )


def datei_pfad(hass: HomeAssistant) -> Path:
    return Path(hass.config.path(IU_DATEI))


def schreiben(pfad: Path, text: str) -> bool:
    """Datei atomar schreiben. True, wenn sich der Inhalt geändert hat.
    (Im Executor aufrufen.)"""
    try:
        if pfad.read_text(encoding="utf-8") == text:
            return False
    except FileNotFoundError:
        pass
    pfad.parent.mkdir(parents=True, exist_ok=True)
    tmp = pfad.with_suffix(".yaml.tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, pfad)
    return True


_PACKAGES_RE = re.compile(r"^\s*packages:\s*!include_dir_(merge_)?named\s+['\"]?/?(config/)?packages/?['\"]?\s*$", re.M)


def include_vorhanden(hass: HomeAssistant) -> bool:
    """Lädt configuration.yaml den Ordner packages/? (Im Executor aufrufen.)"""
    try:
        text = Path(hass.config.path("configuration.yaml")).read_text(encoding="utf-8")
    except OSError:
        return False
    return bool(_PACKAGES_RE.search(text))
